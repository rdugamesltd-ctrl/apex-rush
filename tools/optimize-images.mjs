// Prepares the art for fast loading. Runs the same clean-up the game would do at
// startup (background removal, trimming, scaling, seamless tiles) once, in
// headless Chrome, and saves the result as a small WebP in assets/game/.
// Writes src/assets/built.js so the game loads those instead of the big PNGs
// and does not request images that do not exist, and the preload list in
// index.html so the browser fetches them while Phaser is still downloading.
// File names carry a content hash, so they can be cached forever.
//
// Run it after adding or replacing a file in assets/images/:
//   npm run optimize            (only changed images)
//   npm run optimize -- --force (everything)
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import puppeteer from 'puppeteer-core';
import { startServer } from './server.mjs';
import { ASSETS, IMAGE_DIR } from '../src/assets/manifest.js';
import { pngHash } from './check-images.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = 'assets/game/';
const BUILT_JS = path.join(root, 'src/assets/built.js');
const force = process.argv.includes('--force');

// WebP quality per kind. The car stays lossless: its tyres and paint mask are
// detected from exact pixels at startup.
const quality = (a) => (a.key === 'car' ? 1 : a.kind === 'tile' ? 0.86 : 0.9);

let previous = {};
try {
  previous = (await import(`file:///${BUILT_JS.replace(/\\/g, '/')}?t=${Date.now()}`)).BUILT || {};
} catch {
  /* first run */
}

const BROWSERS = [process.env.BROWSER, 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/google-chrome', '/usr/bin/chromium'].filter(Boolean);
const PORT = Number(process.env.PORT) || 8128;
const server = await startServer(PORT);
const browser = await puppeteer.launch({ executablePath: BROWSERS.find((p) => fs.existsSync(p)), headless: true });
fs.mkdirSync(path.join(root, OUT_DIR), { recursive: true });

const built = {};
const missing = [];
let before = 0;
let after = 0;
try {
  const page = await browser.newPage();
  page.on('console', (m) => process.env.VERBOSE && console.log('  ', m.text()));
  await page.setRequestInterception(true);
  page.on('request', (r) =>
    r.url().endsWith('/__blank') ? r.respond({ contentType: 'text/html', body: '<!DOCTYPE html><title>optimize</title>' }) : r.continue()
  );
  await page.goto(`http://localhost:${PORT}/__blank`);

  for (const a of ASSETS) {
    const srcFile = path.join(root, IMAGE_DIR, `${a.key}.png`);
    if (!fs.existsSync(srcFile)) {
      missing.push(a.key);
      continue;
    }
    const st = fs.statSync(srcFile);
    const stamp = { size: st.size, sha: pngHash(srcFile) };
    const prev = previous[a.key];
    before += st.size;
    // same contents as last time (older builds stored size + date instead of a hash)
    const same = prev && (prev.src?.sha ? prev.src.sha === stamp.sha : prev.src?.size === stamp.size && prev.src?.mtime === Math.round(st.mtimeMs));
    if (!force && same && fs.existsSync(path.join(root, OUT_DIR, prev.file))) {
      built[a.key] = { ...prev, src: stamp };
      after += fs.statSync(path.join(root, OUT_DIR, prev.file)).size;
      console.log(`  ${a.key.padEnd(16)} unchanged`);
      continue;
    }
    const r = await page.evaluate(
      async (url, entry, q) => {
        const { normalizeImage } = await import('/src/assets/normalize.js');
        const img = new Image();
        img.src = url;
        await img.decode();
        const c = normalizeImage(img, entry);
        const blob = await new Promise((res) => c.toBlob(res, 'image/webp', q));
        const bytes = new Uint8Array(await blob.arrayBuffer());
        let bin = '';
        for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
        return { w: c.width, h: c.height, data: btoa(bin) };
      },
      `/${IMAGE_DIR}${a.key}.png`,
      a,
      quality(a)
    );
    const buf = Buffer.from(r.data, 'base64');
    const file = `${a.key}.${crypto.createHash('sha256').update(buf).digest('hex').slice(0, 8)}.webp`;
    fs.writeFileSync(path.join(root, OUT_DIR, file), buf);
    after += buf.length;
    built[a.key] = { file, w: r.w, h: r.h, src: stamp };
    console.log(`  ${a.key.padEnd(16)} ${(st.size / 1024).toFixed(0).padStart(6)} KB png -> ${(buf.length / 1024).toFixed(0).padStart(5)} KB webp  ${r.w}x${r.h}`);
  }
} finally {
  await browser.close();
  server.close();
}

// drop outputs of images that were removed
for (const f of fs.readdirSync(path.join(root, OUT_DIR))) {
  if (f.endsWith('.webp') && !Object.values(built).some((b) => b.file === f)) fs.unlinkSync(path.join(root, OUT_DIR, f));
}

const js = `// Generated by tools/optimize-images.mjs - do not edit. Run \`npm run optimize\` after changing assets/images/.
// BUILT: images already cleaned up and saved as WebP in ${OUT_DIR} (src = the PNG they were made from).
// MISSING: manifest images with no file; the game draws placeholders without requesting them.
export const BUILT_DIR = '${OUT_DIR}';
export const BUILT = ${JSON.stringify(built, null, 2)};
export const MISSING = ${JSON.stringify(missing)};
`;
fs.writeFileSync(BUILT_JS, js);

// let the browser start on the images straight from the HTML
const html = path.join(root, 'index.html');
const START = '<!-- images:start (written by tools/optimize-images.mjs) -->';
const END = '<!-- images:end -->';
const links = Object.values(built)
  .map((b) => `  <link rel="preload" as="image" href="${OUT_DIR}${b.file}">`)
  .join('\n');
let page = fs.readFileSync(html, 'utf8');
const block = `${START}\n${links}\n  ${END}`;
const a = page.indexOf(START);
const b = page.indexOf(END);
if (a >= 0 && b > a) page = page.slice(0, a) + block + page.slice(b + END.length);
else page = page.replace('</head>', `  ${block}\n</head>`);
fs.writeFileSync(html, page);
console.log(`\n${Object.keys(built).length} images: ${(before / 1048576).toFixed(1)} MB of PNG -> ${(after / 1048576).toFixed(2)} MB of WebP. ${missing.length} use placeholders.`);
console.log('Wrote src/assets/built.js and the image preloads in index.html');
